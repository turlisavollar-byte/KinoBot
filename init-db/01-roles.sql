\set ON_ERROR_STOP on
\getenv migrator_password MIGRATOR_PASSWORD
\getenv app_password APP_PASSWORD

SELECT format(
  'CREATE ROLE %I WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD %L',
  'kinobot_migrator',
  :'migrator_password'
)
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'kinobot_migrator')
\gexec

ALTER ROLE kinobot_migrator
  WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS
  PASSWORD :'migrator_password';

SELECT format(
  'CREATE ROLE %I WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD %L',
  'kinobot_app',
  :'app_password'
)
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'kinobot_app')
\gexec

ALTER ROLE kinobot_app
  WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS
  PASSWORD :'app_password';

SELECT format(
  'CREATE ROLE %I WITH NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS',
  'kinobot_user'
)
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'kinobot_user')
\gexec

ALTER ROLE kinobot_user
  WITH NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;

GRANT ALL PRIVILEGES ON DATABASE kinobot_staging TO kinobot_migrator;
GRANT CONNECT ON DATABASE kinobot_staging TO kinobot_app;
GRANT USAGE ON SCHEMA public TO kinobot_user;
ALTER SCHEMA public OWNER TO kinobot_migrator;
GRANT kinobot_user TO kinobot_app;

ALTER DEFAULT PRIVILEGES FOR ROLE kinobot_migrator IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO kinobot_user;
ALTER DEFAULT PRIVILEGES FOR ROLE kinobot_migrator IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO kinobot_user;
