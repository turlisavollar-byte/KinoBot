export type TranslationKey = keyof typeof messages.en;

const STORAGE_KEY = "streamops-locale";
const localeTags: Record<Locale, string> = {
  en: "en-US",
  ru: "ru-RU",
  uz: "uz-UZ",
};

function getInitialLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && LOCALES.includes(saved as Locale)) return saved as Locale;
    const browserLocale = navigator.language.toLowerCase();
    if (browserLocale.startsWith("ru")) return "ru";
    if (browserLocale.startsWith("uz")) return "uz";
  } catch {
    // Storage and navigator can be unavailable during SSR or restricted previews.
  }
  return "uz";
}

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
  formatDate: (date: string | Date, options?: Intl.DateTimeFormatOptions) => string;
  formatNumber: (value: number) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(getInitialLocale);

  const handleSetLocale = (nextLocale: Locale) => {
    setLocaleState(nextLocale);
    try {
      localStorage.setItem(STORAGE_KEY, nextLocale);
    } catch {
      // The in-memory selection still works when storage is blocked.
    }
  };

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale: handleSetLocale,
    t: (key, values) => {
      const template = messages[locale][key] ?? messages.en[key] ?? key;
      return values
        ? template.replace(/\{(\w+)\}/g, (_: string, name: string) => String(values[name] ?? `{${name}}`))
        : template;
    },
    formatDate: (date, options) => new Intl.DateTimeFormat(localeTags[locale], options).format(new Date(date)),
    formatNumber: (value) => new Intl.NumberFormat(localeTags[locale]).format(value),
  }), [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within I18nProvider");
  return context;
}
